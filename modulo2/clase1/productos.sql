-- prodcutos
CREATE TABLE productos (
	ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(50) NOT NULL UNIQUE,
	precio NUMERIC(12,2) NOT NULL CHECK (precio >= 0),
	stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
)

